// Dono: g04. Conversão entre códigos HID (página 0x07) e virtual keycodes do macOS (kVK_*).
namespace ConnectDesktop.Platform.Mac;

/// <summary>Conversão entre códigos HID (USB HID Usage Tables, página 0x07) e kVK_* do macOS.</summary>
public static class KeyMap
{
    // (HID, kVK_*). Ctrl do Windows (E0/E4) = Control; Win/GUI (E3/E7) = Command.
    private static readonly (ushort Hid, ushort Mac)[] Pairs =
    {
        // Letras A-Z
        (0x04, 0x00), (0x05, 0x0B), (0x06, 0x08), (0x07, 0x02), (0x08, 0x0E), (0x09, 0x03), (0x0A, 0x05),
        (0x0B, 0x04), (0x0C, 0x22), (0x0D, 0x26), (0x0E, 0x28), (0x0F, 0x25), (0x10, 0x2E), (0x11, 0x2D),
        (0x12, 0x1F), (0x13, 0x23), (0x14, 0x0C), (0x15, 0x0F), (0x16, 0x01), (0x17, 0x11), (0x18, 0x20),
        (0x19, 0x09), (0x1A, 0x0D), (0x1B, 0x07), (0x1C, 0x10), (0x1D, 0x06),
        // Números 1-0
        (0x1E, 0x12), (0x1F, 0x13), (0x20, 0x14), (0x21, 0x15), (0x22, 0x17), (0x23, 0x16), (0x24, 0x1A),
        (0x25, 0x1C), (0x26, 0x19), (0x27, 0x1D),
        // Controles e pontuação
        (0x28, 0x24), // Enter -> Return
        (0x29, 0x35), // Esc -> Escape
        (0x2A, 0x33), // Backspace -> Delete
        (0x2B, 0x30), // Tab
        (0x2C, 0x31), // Space
        (0x2D, 0x1B), // -
        (0x2E, 0x18), // =
        (0x2F, 0x21), // [
        (0x30, 0x1E), // ]
        (0x31, 0x2A), // \
        (0x33, 0x29), // ;
        (0x34, 0x27), // '
        (0x35, 0x32), // `
        (0x36, 0x2B), // ,
        (0x37, 0x2F), // .
        (0x38, 0x2C), // /
        (0x39, 0x39), // CapsLock
        (0x64, 0x0A), // Non-US \ | -> kVK_ISO_Section
        // F1-F12
        (0x3A, 0x7A), (0x3B, 0x78), (0x3C, 0x63), (0x3D, 0x76), (0x3E, 0x60), (0x3F, 0x61),
        (0x40, 0x62), (0x41, 0x64), (0x42, 0x65), (0x43, 0x6D), (0x44, 0x67), (0x45, 0x6F),
        // Navegação
        (0x4A, 0x73), // Home
        (0x4B, 0x74), // PageUp
        (0x4C, 0x75), // Delete (forward)
        (0x4D, 0x77), // End
        (0x4E, 0x79), // PageDown
        (0x4F, 0x7C), // Right
        (0x50, 0x7B), // Left
        (0x51, 0x7D), // Down
        (0x52, 0x7E), // Up
        // Teclado numérico
        (0x53, 0x47), // NumLock -> Keypad Clear
        (0x54, 0x4B), // /
        (0x55, 0x43), // *
        (0x56, 0x4E), // -
        (0x57, 0x45), // +
        (0x58, 0x4C), // Enter
        (0x59, 0x53), (0x5A, 0x54), (0x5B, 0x55), (0x5C, 0x56), (0x5D, 0x57),
        (0x5E, 0x58), (0x5F, 0x59), (0x60, 0x5B), (0x61, 0x5C), (0x62, 0x52),
        (0x63, 0x41), // .
        (0x67, 0x51), // =
        // F13-F20
        (0x68, 0x69), (0x69, 0x6B), (0x6A, 0x71), (0x6B, 0x6A), (0x6C, 0x40), (0x6D, 0x4F), (0x6E, 0x50), (0x6F, 0x5A),
        // Modificadores
        (0xE0, 0x3B), // LeftCtrl -> Control
        (0xE1, 0x38), // LeftShift -> Shift
        (0xE2, 0x3A), // LeftAlt -> Option
        (0xE3, 0x37), // LeftGUI -> Command
        (0xE4, 0x3E), // RightCtrl -> RightControl
        (0xE5, 0x3C), // RightShift -> RightShift
        (0xE6, 0x3D), // RightAlt -> RightOption
        (0xE7, 0x36), // RightGUI -> RightCommand
    };

    private static readonly Dictionary<ushort, ushort> HidToMacMap = new();
    private static readonly Dictionary<ushort, ushort> MacToHidMap = new();

    static KeyMap()
    {
        foreach ((ushort hid, ushort mac) in Pairs)
        {
            HidToMacMap.TryAdd(hid, mac);
            MacToHidMap.TryAdd(mac, hid);
        }
    }

    /// <summary>Converte um virtual keycode do macOS (kVK_*) em código HID. Retorna null se não houver mapeamento.</summary>
    public static ushort? MacToHid(ushort kc)
    {
        return MacToHidMap.TryGetValue(kc, out ushort hid) ? (ushort?)hid : null;
    }

    /// <summary>Converte um código HID em virtual keycode do macOS (kVK_*). Retorna null se não houver mapeamento.</summary>
    public static ushort? HidToMac(ushort hid)
    {
        return HidToMacMap.TryGetValue(hid, out ushort kc) ? (ushort?)kc : null;
    }
}
